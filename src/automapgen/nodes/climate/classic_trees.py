"""Classic Trees (optional): a startup script that assigns the base game's TF2 trees to own tree sets, which the
import tree mixes into the forest."""

from __future__ import annotations

from string import Template
from typing import NamedTuple

from automapgen.graph import NodeParams, node
from automapgen.nodes.climate.preset import ClimatePreset
from automapgen.nodes.mods import CONTENT, ModFiles

SCRIPT_NAME = "dhe_classic_trees.script"

_TEMPLATE = Template('''-- generated by tf3gen
local SETS = {
$entries}

function data()
	return {
		postRunFn = function(params)
			for res, set in pairs(SETS) do
				local id = api.res.modelRep.find(res)
				if id and id >= 0 then
					local t = api.res.modelRep.getAsTable(id)
					t.metadata = t.metadata or {}
					t.metadata.categoryList = t.metadata.categoryList or { categories = {} }
					local cats = t.metadata.categoryList.categories or {}
					table.insert(cats, set)
					t.metadata.categoryList.categories = cats
					api.res.modelRep.setAsTable(id, t)
				else
					print("[dhe_classic_trees] model not found: " .. res)
				end
			end
			print("[dhe_classic_trees] tree sets assigned")
		end,
	}
end
''')


class ClassicTreesParams(NodeParams):
    climate: ClimatePreset
    """The climate preset (its forest names the Classic Trees sets)."""


class ClassicTrees(NamedTuple):
    files: ModFiles
    post_run_script: str


@node("climate.classic_trees")
def classic_trees(mod_id: str, params: ClassicTreesParams) -> ClassicTrees:
    """The startup script of the Classic Trees and its entry for mod.json; nothing when they are off."""
    classic = params.climate.forest.classic
    if classic is None:
        return ClassicTrees(ModFiles(()), "")
    entries = "".join(f'\t["::/assets/vegetation/trees/{model}/{model}.mdl"] = "{name}",\n'
                      for name, (_, models) in classic.sets.items() for model in models)
    script = _TEMPLATE.substitute(entries=entries).encode("utf-8")
    return ClassicTrees(ModFiles.of({f"{CONTENT}{SCRIPT_NAME}.lua": script}), f"{mod_id}::/{SCRIPT_NAME}@postRunFn")
