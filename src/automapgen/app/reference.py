"""Reference for AI assistants and map makers, generated from the code: every node type with its parameters (from the
parameter schemas) and every built-in graph with its exposed parameters (`automapgen reference`).

Generated, so it cannot drift from the code; a unit test checks that the committed files are current.
"""

from __future__ import annotations

import json
from collections.abc import Iterable, Mapping
from typing import Any

from automapgen.graph.catalog import NodeCatalog
from automapgen.graph.document import GraphDocument, NodeEntry
from automapgen.graph.library import FolderLibrary
from automapgen.graph.node import Arity, NodeSpec

GENERATED = "<!-- Generated by `automapgen reference` - do not edit; change the code and generate again. -->"
_MAX_DEFAULT = 100        # longer defaults are cut; the value types section shows their parts


def _anchor(name: str) -> str:
    """GitHub heading anchor of a node type, graph id or type name."""
    return name.lower().replace(".", "")


def _one_line(text: str) -> str:
    return " ".join(text.split())


class SchemaText:
    """JSON schemas of parameter models as Markdown: one line per field, named tables as links to their section."""

    def __init__(self, definitions: Mapping[str, Any]) -> None:
        self._defs = definitions

    def is_table(self, name: str) -> bool:
        """A definition with its own section (a table with fields); others are written inline."""
        return "properties" in self._defs.get(name, {})

    def type_text(self, schema: Mapping[str, Any]) -> str:
        if "$ref" in schema:
            name = str(schema["$ref"]).rsplit("/", 1)[-1]
            return f"[{name}](#{_anchor(name)})" if self.is_table(name) else self.type_text(self._defs[name])
        if "const" in schema:
            return json.dumps(schema["const"])
        if "enum" in schema:
            return " \\| ".join(json.dumps(v) for v in schema["enum"])
        for key in ("anyOf", "oneOf"):
            if key in schema:
                return " \\| ".join(self.type_text(s) for s in schema[key])
        kind = schema.get("type")
        if kind == "null":
            return "none"
        if kind == "array":
            if "prefixItems" in schema:
                return "[" + ", ".join(self.type_text(s) for s in schema["prefixItems"]) + "]"
            return f"list of {self.type_text(schema.get('items', {}))}"
        if kind == "object":
            values = schema.get("additionalProperties")
            return f"table of {self.type_text(values)}" if isinstance(values, dict) else "table"
        return str(kind or "any")

    def field_lines(self, schema: Mapping[str, Any]) -> list[str]:
        required = set(schema.get("required", []))
        return [self._field(name, field, name in required) for name, field in schema.get("properties", {}).items()]

    def _field(self, name: str, field: Mapping[str, Any], required: bool) -> str:
        details = [self.type_text(field)]
        if required:
            details.append("required")
        elif "default" in field:
            default = json.dumps(field["default"], ensure_ascii=False)
            details.append(f"default `{default if len(default) <= _MAX_DEFAULT else default[:_MAX_DEFAULT] + ' ...'}`")
        if "unit" in field:
            details.append(f"unit {field['unit']}")
        for key, sign in (("minimum", ">="), ("exclusiveMinimum", ">"), ("maximum", "<="), ("exclusiveMaximum", "<")):
            if key in field:
                details.append(f"{sign} {field[key]}")
        description = _one_line(str(field.get("description", "")))
        return f"- `{name}` ({', '.join(details)}){': ' + description if description else ''}"


class NodeReference:
    """All node types: description, ports, parameters; then the value types (tables) the parameters use."""

    def __init__(self, catalog: NodeCatalog) -> None:
        self._specs = catalog.specs()
        self._schemas = {s.type_id: s.params_model.model_json_schema() for s in self._specs}
        self._text = SchemaText({k: v for schema in self._schemas.values()
                                 for k, v in schema.get("$defs", {}).items()})

    def markdown(self) -> str:
        lines = [GENERATED, "", "# Node types", "",
                 "Every node type: what it does, its ports (`name: data type`) and its parameters (type, default, "
                 "unit, limits). A parameter whose type is a link is a table; its fields are under *Value types*. "
                 "Graphs: [graphs.md](graphs.md); how to change things: [README.md](README.md).", ""]
        for spec in self._specs:
            lines += self._node(spec)
        lines += ["# Value types", ""]
        for name in sorted(self._text_defs()):
            lines += self._value_type(name)
        return "\n".join(lines).rstrip() + "\n"

    def _node(self, spec: NodeSpec) -> list[str]:
        lines = [f"## {spec.type_id}", "", f"Version {spec.version}" + (", writes files" if spec.side_effects else ""),
                 ""]
        if spec.description:
            lines += [spec.description.strip(), ""]
        ins = ", ".join(f"`{p.name}: {p.type.name}`" + ("" if p.arity is Arity.ONE else f" ({p.arity.value})")
                        for p in spec.inputs.values())
        outs = ", ".join(f"`{p.name}: {p.type.name}`" for p in spec.outputs.values())
        lines += [f"Inputs: {ins or '-'}  ", f"Outputs: {outs or '-'}", ""]
        fields = self._text.field_lines(self._schemas[spec.type_id])
        return lines + (["Parameters:", "", *fields, ""] if fields else [])

    def _text_defs(self) -> Iterable[str]:
        return {k for schema in self._schemas.values() for k in schema.get("$defs", {}) if self._text.is_table(k)}

    def _value_type(self, name: str) -> list[str]:
        schema = next(s["$defs"][name] for s in self._schemas.values() if name in s.get("$defs", {}))
        lines = [f"## {name}", ""]
        if schema.get("description"):
            lines += [schema["description"].strip(), ""]
        return lines + self._text.field_lines(schema) + [""]


class GraphReference:
    """All built-in graphs: purpose, what they extend, exposed parameters (and the node parameters they set), nodes."""

    def __init__(self, library: FolderLibrary) -> None:
        self._library = library

    def markdown(self) -> str:
        lines = [GENERATED, "", "# Graphs", "",
                 "Every built-in graph. *Exposed parameters* are the names a parameter set gives in `[params]` (a "
                 "project) or `[defaults]` (a preset); each sets the node parameters it points to (`node.parameter`, "
                 "types in [nodes.md](nodes.md)). A node of type `graph:<id>` is a subgraph. Diagrams: "
                 "`automapgen show <id>` or docsHuman/graphs/<id>.md.", ""]
        for graph_id in self._library.ids():
            document = self._library.get(graph_id)
            if document is not None:
                lines += self._graph(document)
        return "\n".join(lines).rstrip() + "\n"

    def _graph(self, document: GraphDocument) -> list[str]:
        lines = [f"## {document.id}", ""]
        if document.title:
            lines += [f"**{document.title}**", ""]
        if document.description:
            lines += [_one_line(document.description), ""]
        if document.extends:
            lines += [f"Extends [{document.extends}](#{_anchor(document.extends)}): nodes, links and parameters of "
                      "that graph, changed as listed here.", ""]
        if document.inputs or document.outputs:
            lines += [f"Inputs: {self._ports(document.inputs)}  ", f"Outputs: {self._ports(document.outputs)}", ""]
        if document.params:
            lines += ["Exposed parameters:", ""]
            for name, exposed in document.params.items():
                value = "" if exposed.value is None else f", default `{json.dumps(exposed.value, ensure_ascii=False)}`"
                description = f": {_one_line(exposed.description)}" if exposed.description else ""
                lines.append(f"- `{name}` -> {', '.join(f'`{t}`' for t in exposed.to)}{value}{description}")
            lines.append("")
        if document.nodes:
            lines += ["Nodes:", "", *(self._node(name, node) for name, node in document.nodes.items()), ""]
        if document.remove:
            lines += [f"Removed nodes: {', '.join(f'`{n}`' for n in document.remove)}", ""]
        return lines

    @staticmethod
    def _ports(ports: Mapping[str, str]) -> str:
        return ", ".join(f"`{name}: {kind}`" for name, kind in ports.items()) or "-"

    @staticmethod
    def _node(name: str, node: NodeEntry) -> str:
        kind = node.type
        target = (f"[{kind}](#{_anchor(kind.removeprefix('graph:'))})" if kind.startswith("graph:")
                  else f"[{kind}](nodes.md#{_anchor(kind)})")
        note = f": {_one_line(node.note)}" if node.note else ""
        return f"- `{name}` {target}{note}"
